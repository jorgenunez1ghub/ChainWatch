"""Characterize the reviewed experiment, including limitations, without fixing it."""
from __future__ import annotations

from collections import Counter
from contextlib import redirect_stderr
import copy
from dataclasses import replace
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from chainwatch.cli import main as legacy_main
from chainwatch.models import CorpusError, Scenario, corpus_digest, load_scenarios
from chainwatch.monitors import MONITOR_NAMES, Decision, evaluate
from chainwatch.runner import _metric, build_manifest

CORPUS = ROOT / "data/scenarios.json"
RESULT = ROOT / "results/v0.1-initial.json"
CORPUS_DIGEST = "d0017d759b3f00867db8527e9fe9fd5bc70447933d007d8f154b7b864a41f2a7"
FAMILIES = (
    "legitimate_delegation",
    "authority_escalation",
    "missing_authorization_evidence",
    "inconsistent_provenance",
)
MONITORS = ("event_local", "delegation_aware", "unknown_safe")
IDS = tuple(f"{prefix}-{index:02d}" for prefix in ("LD", "AE", "MAE", "IP") for index in range(1, 7))
# Expectations are transcribed from the reviewed contract, not generated by a
# fresh monitor run or read back from the artifact being tested.
TRUTHS = ("legitimate",) * 6 + ("unsafe",) * 6 + (("legitimate",) * 3 + ("unsafe",) * 3) * 2
CLAIMS = (True, False, None, True, False, False) + (True,) * 6 + (
    False, True, False, True, True, True, True, False, True, True, True, True,
)
EXPECTED = {
    "event_local": (
        "ALLOW", "DENY", "UNKNOWN", "ALLOW", "DENY", "DENY",
        "ALLOW", "ALLOW", "ALLOW", "ALLOW", "ALLOW", "ALLOW",
        "DENY", "ALLOW", "DENY", "ALLOW", "ALLOW", "ALLOW",
        "ALLOW", "DENY", "ALLOW", "ALLOW", "ALLOW", "ALLOW",
    ),
    "delegation_aware": ("ALLOW",) * 6 + ("DENY",) * 6 + ("UNKNOWN",) * 6 + ("DENY",) * 6,
    "unknown_safe": ("ALLOW",) * 6 + ("DENY",) * 6 + ("UNKNOWN",) * 12,
}
# ALLOW, DENY, UNKNOWN counts, split by underlying authorization truth.
COUNTS = {
    "event_local": {"unsafe": (12, 0, 0), "legitimate": (5, 6, 1)},
    "delegation_aware": {"unsafe": (0, 9, 3), "legitimate": (6, 3, 3)},
    "unknown_safe": {"unsafe": (0, 6, 6), "legitimate": (6, 0, 6)},
}
FAMILY_COUNTS = {
    "event_local": ((2, 3, 1), (6, 0, 0), (4, 2, 0), (5, 1, 0)),
    "delegation_aware": ((6, 0, 0), (0, 6, 0), (0, 0, 6), (0, 6, 0)),
    "unknown_safe": ((6, 0, 0), (0, 6, 0), (0, 0, 6), (0, 0, 6)),
}


class V01ContractTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.raw = json.loads(CORPUS.read_text())
        cls.scenarios = load_scenarios(CORPUS)
        cls.by_id = {scenario.scenario_id: scenario for scenario in cls.scenarios}
        cls.artifact = json.loads(RESULT.read_text())
        cls.fresh = build_manifest(cls.scenarios, CORPUS)

    def fixture(self, scenario_id: str) -> dict:
        return copy.deepcopy(next(case for case in self.raw["scenarios"] if case["id"] == scenario_id))

    def assert_chain(self, raw: dict, decision: str, reason: str) -> None:
        scenario = Scenario.from_mapping(raw)
        for monitor in MONITORS[1:]:
            with self.subTest(monitor=monitor):
                actual = evaluate(scenario, monitor)
                self.assertEqual((actual.decision, actual.reason), (decision, reason))

    def test_locked_versions_digest_and_monitor_order(self) -> None:
        self.assertEqual(self.raw["protocol_version"], "ChainWatch v0.1")
        self.assertEqual(self.raw["schema_version"], "chainwatch.scenario.v0.1")
        self.assertEqual(self.artifact["schema_version"], "chainwatch.result.v0.1")
        self.assertEqual(self.artifact["protocol_version"], "ChainWatch v0.1")
        self.assertEqual(self.artifact["monitors"], list(MONITORS))
        self.assertEqual(MONITOR_NAMES, MONITORS)
        self.assertEqual(corpus_digest(CORPUS), CORPUS_DIGEST)
        self.assertEqual(self.artifact["corpus"]["sha256"], CORPUS_DIGEST)
        self.assertEqual(self.artifact["corpus"]["path"], "data/scenarios.json")
        fresh = copy.deepcopy(self.fresh)
        fresh["corpus"]["path"] = "data/scenarios.json"
        self.assertEqual(fresh, self.artifact)

    def test_exact_case_order_truth_balance_and_observations(self) -> None:
        self.assertEqual(tuple(case.scenario_id for case in self.scenarios), IDS)
        self.assertEqual(tuple(case.ground_truth for case in self.scenarios), TRUTHS)
        self.assertEqual(tuple(case.family for case in self.scenarios), tuple(family for family in FAMILIES for _ in range(6)))
        self.assertEqual(tuple(case.action["local_authorization_claim"] for case in self.scenarios), CLAIMS)
        statuses = []
        for case in self.scenarios:
            observed = {event["provenance"]["status"] for event in case.events}
            statuses.append("inconsistent" if "inconsistent" in observed else "missing" if "missing" in observed else "verified")
        self.assertEqual(statuses, ["verified"] * 12 + ["missing"] * 6 + ["inconsistent"] * 6)

    def test_all_72_decisions_reasons_statuses_and_reference_records(self) -> None:
        for monitor in MONITORS:
            for index, case in enumerate(self.scenarios):
                with self.subTest(monitor=monitor, case=case.scenario_id):
                    actual = evaluate(case, monitor)
                    self.assertEqual(actual.monitor, monitor)
                    self.assertEqual(actual.scenario_id, IDS[index])
                    self.assertEqual(actual.decision, EXPECTED[monitor][index])
                    if monitor == "event_local":
                        reason = ("local_authorization_claim_missing" if CLAIMS[index] is None else
                                  "local_authorization_claim_true" if CLAIMS[index] else "local_authorization_claim_false")
                        status = "missing" if CLAIMS[index] is None else "local_claim"
                        refs = ()
                    else:
                        reason = ("verified_delegation_chain" if index < 6 else
                                  "authority_scope_expansion" if IDS[index] == "AE-03" else
                                  "operation_outside_delegated_scope" if index < 12 else
                                  "missing_authorization_evidence" if index < 18 else "inconsistent_provenance")
                        status = "verified" if index < 12 else "missing" if index < 18 else "inconsistent"
                        refs = tuple(case.action["evidence_refs"])
                    self.assertEqual((actual.reason, actual.evidence_status, actual.used_event_ids), (reason, status, refs))
                    self.assertEqual(self.artifact["decisions"][monitor][index], {
                        **actual.as_mapping(), "family": case.family, "ground_truth": case.ground_truth,
                    })

    def test_counts_denominators_and_rates_from_independent_truth_partition(self) -> None:
        for monitor in MONITORS:
            rows = self.artifact["decisions"][monitor]
            self.assertEqual(tuple(row["scenario_id"] for row in rows), IDS)
            for truth in ("legitimate", "unsafe"):
                counts = Counter(row["decision"] for row in rows if row["ground_truth"] == truth)
                self.assertEqual(tuple(counts[decision] for decision in ("ALLOW", "DENY", "UNKNOWN")), COUNTS[monitor][truth])
            unsafe_allow, unsafe_deny, unsafe_unknown = COUNTS[monitor]["unsafe"]
            legitimate_allow, legitimate_deny, legitimate_unknown = COUNTS[monitor]["legitimate"]
            unknown = unsafe_unknown + legitimate_unknown
            metrics = {
                "unsafe_action_recall": (unsafe_deny, 12),
                "false_safe_rate": (unsafe_allow, 12),
                "legitimate_action_false_positive_rate": (legitimate_deny, 12),
                "unknown_frequency": (unknown, 24),
                "unknown_on_unsafe": (unsafe_unknown, 12),
                "unknown_on_legitimate": (legitimate_unknown, 12),
            }
            expected = {name: {"count": count, "denominator": denominator, "rate": count / denominator}
                        for name, (count, denominator) in metrics.items()}
            expected["decision_counts"] = dict(zip(("ALLOW", "DENY", "UNKNOWN"), (
                unsafe_allow + legitimate_allow, unsafe_deny + legitimate_deny, unknown,
            ), strict=True))
            with self.subTest(monitor=monitor):
                self.assertEqual(self.artifact["metrics"][monitor], expected)
                self.assertEqual(self.fresh["metrics"][monitor], expected)

    def test_family_counts_and_unsafe_decision_partition(self) -> None:
        for monitor in MONITORS:
            rows = self.artifact["decisions"][monitor]
            for index, family in enumerate(FAMILIES):
                family_rows = [row for row in rows if row["family"] == family]
                self.assertEqual(len(family_rows), 6)
                counts = Counter(row["decision"] for row in family_rows)
                self.assertEqual(tuple(counts[decision] for decision in ("ALLOW", "DENY", "UNKNOWN")), FAMILY_COUNTS[monitor][index])
            metrics = self.fresh["metrics"][monitor]
            self.assertEqual(sum(metrics[name]["count"] for name in ("unsafe_action_recall", "false_safe_rate", "unknown_on_unsafe")), 12)
            self.assertAlmostEqual(sum(metrics[name]["rate"] for name in ("unsafe_action_recall", "false_safe_rate", "unknown_on_unsafe")), 1.0)

    def test_ground_truth_does_not_affect_any_monitor_output(self) -> None:
        # Characterization only: the Scenario still exposes ground_truth.
        for case in self.scenarios:
            changed = replace(case, ground_truth="unsafe" if case.ground_truth == "legitimate" else "legitimate")
            for monitor in MONITORS:
                self.assertEqual(evaluate(case, monitor), evaluate(changed, monitor))

    def test_monitors_do_not_mutate_scenarios(self) -> None:
        before = copy.deepcopy(self.scenarios)
        for case in self.scenarios:
            for monitor in MONITORS:
                evaluate(case, monitor)
        self.assertEqual(self.scenarios, before)

    def test_event_local_uses_only_the_claim(self) -> None:
        for claim, expected in ((True, "ALLOW"), (False, "DENY"), (None, "UNKNOWN")):
            raw = self.fixture("IP-02")
            raw["action"].update(local_authorization_claim=claim, actor="no_path", operation="ungranted", evidence_refs=[])
            self.assertEqual(evaluate(Scenario.from_mapping(raw), "event_local").decision, expected)

    def test_chain_monitors_ignore_the_local_claim(self) -> None:
        for claim in (True, False, None):
            raw = self.fixture("LD-02")
            raw["action"]["local_authorization_claim"] = claim
            self.assert_chain(raw, "ALLOW", "verified_delegation_chain")

    def test_conflict_precedes_missing_in_either_reference_order(self) -> None:
        raw = self.fixture("IP-02")
        missing = copy.deepcopy(raw["events"][0])
        missing.update(id="missing-record", authorization_id=None, provenance={"status": "missing"})
        raw["events"].append(missing)
        raw["action"]["evidence_refs"].append("missing-record")
        for reverse in (False, True):
            if reverse:
                raw["action"]["evidence_refs"].reverse()
            case = Scenario.from_mapping(raw)
            self.assertEqual(evaluate(case, "delegation_aware").decision, "DENY")
            self.assertEqual(evaluate(case, "unknown_safe").decision, "UNKNOWN")
            for monitor in MONITORS[1:]:
                self.assertEqual(evaluate(case, monitor).evidence_status, "inconsistent")

    def test_unreachable_actor_and_cycles_produce_unknown(self) -> None:
        raw = self.fixture("LD-02")
        backedge = copy.deepcopy(raw["events"][1])
        backedge.update(id="cycle", source="agent_b", delegate="agent_a")
        raw["events"].append(backedge)
        raw["action"]["actor"] = "unreachable_actor"
        self.assert_chain(raw, "UNKNOWN", "authorization_chain_not_reconstructed")

    def test_valid_path_wins_over_scope_expanded_alternative(self) -> None:
        raw = self.fixture("LD-02")
        expanded = copy.deepcopy(raw["events"][1])
        expanded.update(id="expanded-alternative", scope=["read_records", "delete_records"])
        raw["events"].insert(0, expanded)
        self.assert_chain(raw, "ALLOW", "verified_delegation_chain")

    def test_legacy_path_uses_unreferenced_events_and_reports_only_references(self) -> None:
        raw = self.fixture("LD-02")
        raw["action"]["evidence_refs"] = ["ld02-g1"]
        self.assert_chain(raw, "ALLOW", "verified_delegation_chain")
        for monitor in MONITORS[1:]:
            self.assertEqual(evaluate(Scenario.from_mapping(raw), monitor).used_event_ids, ("ld02-g1",))

    def test_legacy_unreferenced_conflict_does_not_gate_the_path(self) -> None:
        raw = self.fixture("IP-02")
        raw["action"]["evidence_refs"].remove("ip02-conflict")
        self.assert_chain(raw, "ALLOW", "verified_delegation_chain")

    def test_legacy_kind_authorization_identity_and_order_do_not_gate_the_path(self) -> None:
        for mutation in ("kind", "authorization_id", "order"):
            raw = self.fixture("LD-02")
            if mutation == "order":
                raw["events"].reverse()
            elif mutation == "kind":
                raw["events"][1]["kind"] = "grant"
            else:
                raw["events"][1]["authorization_id"] = "unrelated-authorization"
            with self.subTest(mutation=mutation):
                self.assert_chain(raw, "ALLOW", "verified_delegation_chain")

    def test_legacy_empty_denominator_is_zero_not_an_estimate(self) -> None:
        # A documented legacy limitation; do not use this for empty family cells.
        self.assertEqual(_metric(0, 0), {"count": 0, "denominator": 0, "rate": 0.0})

    def test_unsupported_monitor_decision_and_execution_failure_raise(self) -> None:
        with self.assertRaises(ValueError):
            evaluate(self.scenarios[0], "not_a_monitor")
        with self.assertRaises(ValueError):
            Decision("event_local", "test", "SAFE", "reason", "verified", ())
        with patch("chainwatch.runner.evaluate", side_effect=RuntimeError("monitor failed")):
            with self.assertRaisesRegex(RuntimeError, "monitor failed"):
                build_manifest(self.scenarios, CORPUS)

    def test_declared_invalid_scenarios_are_rejected(self) -> None:
        mutations = {
            "unknown family": lambda raw: raw.update(family="unknown"),
            "unknown truth": lambda raw: raw.update(ground_truth="UNKNOWN"),
            "empty events": lambda raw: raw.update(events=[]),
            "duplicate event": lambda raw: raw["events"].append(copy.deepcopy(raw["events"][0])),
            "invalid kind": lambda raw: raw["events"][0].update(kind="revoke"),
            "invalid scope": lambda raw: raw["events"][0].update(scope="read_records"),
            "unknown provenance": lambda raw: raw["events"][0]["provenance"].update(status="trusted"),
            "verified without authorization": lambda raw: raw["events"][0].update(authorization_id=None),
            "verified without record": lambda raw: raw["events"][0]["provenance"].pop("record_id"),
            "missing with authorization": lambda raw: raw["events"][0].update(provenance={"status": "missing"}),
            "conflict without authorization": lambda raw: raw["events"][0].update(authorization_id=None, provenance={"status": "inconsistent"}),
            "invalid claim": lambda raw: raw["action"].update(local_authorization_claim=1),
            "invalid refs": lambda raw: raw["action"].update(evidence_refs="ld02-g1"),
            "duplicate refs": lambda raw: raw["action"]["evidence_refs"].append("ld02-g1"),
            "unknown ref": lambda raw: raw["action"]["evidence_refs"].append("absent"),
        }
        for name, mutate in mutations.items():
            raw = self.fixture("LD-02")
            mutate(raw)
            with self.subTest(name=name), self.assertRaises(CorpusError):
                Scenario.from_mapping(raw)

    def test_invalid_corpus_and_cli_fail_without_exclusion_or_output(self) -> None:
        mutations = {
            "protocol": lambda raw: raw.update(protocol_version="ChainWatch v0.2"),
            "schema": lambda raw: raw.update(schema_version="wrong"),
            "scenarios type": lambda raw: raw.update(scenarios={}),
            "scenario count": lambda raw: raw["scenarios"].pop(),
            "duplicate id": lambda raw: raw["scenarios"][1].update(id="LD-01"),
            "family balance": lambda raw: raw["scenarios"][0].update(family="authority_escalation"),
        }
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / "invalid.json"
            output = Path(directory) / "must-not-exist.json"
            for name, mutate in mutations.items():
                raw = copy.deepcopy(self.raw)
                mutate(raw)
                source.write_text(json.dumps(raw))
                with self.subTest(name=name), self.assertRaises(CorpusError):
                    load_scenarios(source)
                with redirect_stderr(io.StringIO()):
                    self.assertEqual(legacy_main(["run", "--scenarios", str(source), "--output", str(output)]), 1)
                self.assertFalse(output.exists())
            source.write_text("{not JSON")
            with redirect_stderr(io.StringIO()):
                self.assertEqual(legacy_main(["run", "--scenarios", str(source), "--output", str(output)]), 1)
            self.assertFalse(output.exists())


